/**
 * AI Category Generator
 *
 * This script loads the current category list,
 * sends it to your AI model for expansion/refinement,
 * and rewrites categories.js with the updated list.
 *
 * You can run it manually:
 *    node categories-ai-generator.js
 *
 * Or integrate it into CI/CD or a scheduled job.
 */

import fs from "fs";
import path from "path";
import { DEFAULT_CATEGORIES } from "./categories.js";
import { generateWithAI } from "../ai/aiClient.js"; 
// ^ You already have an AI client in your repo.
//   If not, I can generate one for you.

const categoriesFile = path.resolve(
  path.dirname(new URL(import.meta.url).pathname),
  "categories.js"
);

async function generateNewCategories() {
  console.log("🔧 Loading current categories...");
  console.log(DEFAULT_CATEGORIES);

  console.log("🤖 Sending categories to AI for refinement...");

  const prompt = `
You are Rewrite Labs' category engine.

Given this list of business categories:

${JSON.stringify(DEFAULT_CATEGORIES, null, 2)}

Expand and refine the list into a more complete, modern, globally relevant set of business categories.

Rules:
- Keep names simple and lowercase.
- No duplicates.
- No ultra-niche categories.
- No more than 40 categories.
- Return ONLY a JSON array of strings.
`;

  const aiResponse = await generateWithAI(prompt);

  let newCategories;
  try {
    newCategories = JSON.parse(aiResponse);
  } catch (err) {
    console.error("❌ AI returned invalid JSON:", aiResponse);
    throw err;
  }

  console.log("✅ AI generated new categories:");
  console.log(newCategories);

  console.log("📝 Writing updated categories.js...");

  const fileContent = `// File: engine/discovery/categories.js

/**
 * Centralized category list for all sweepers.
 * Auto-generated by categories-ai-generator.js
 */

export const DEFAULT_CATEGORIES = ${JSON.stringify(newCategories, null, 2)};

/**
 * Apply category filtering from CLI args or environment variables.
 */
export function applyCategoryFilter(categories, rawFilter) {
  if (!rawFilter) return categories;

  const filterList = rawFilter
    .split(",")
    .map(c => c.trim().toLowerCase())
    .filter(Boolean);

  const filtered = categories.filter(cat =>
    filterList.includes(cat.toLowerCase())
  );

  console.log("Category filter applied:", filtered);
  return filtered;
}
`;

  fs.writeFileSync(categoriesFile, fileContent, "utf-8");

  console.log("🎉 categories.js updated successfully!");
}

generateNewCategories().catch(err => {
  console.error("❌ Failed to generate categories:", err);
  process.exit(1);
});